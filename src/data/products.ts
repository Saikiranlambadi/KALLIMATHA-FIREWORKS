export const WHATSAPP_BASE_URL = `https://wa.me/${WHATSAPP_NUMBER}`;

export const generateWhatsAppLink = (message: string) => {
  return `${WHATSAPP_BASE_URL}?text=${encodeURIComponent(message.trim())}`;
};

export const generateProductEnquiryLink = (product: Product) => {
  const message = `Hello Kallimatha Fireworks team! 🎆

I am interested in ordering:
✨ *Product:* ${product.name}
💰 *Price:* ₹${product.price}
📦 *Packing:* ${product.piecesPerBox}
🏷️ *Category:* ${product.category.toUpperCase().replace('-', ' ')}

Kindly share availability and order booking details.
Thank you!`;
  return generateWhatsAppLink(message);
};

export const generateCartEnquiryLink = (items: { product: Product; quantity: number }[]) => {
  if (items.length === 0) return WHATSAPP_BASE_URL;

  let itemList = '';
  let totalPrice = 0;
  items.forEach((item, index) => {
    const itemTotal = item.product.price * item.quantity;
    totalPrice += itemTotal;
    itemList += `${index + 1}. *${item.product.name}* (Qty: ${item.quantity}) - ₹${item.product.price}/box (${item.product.piecesPerBox})\n`;
  });

  const message = `Hello Kallimatha Fireworks team! 🎆

I would like to place an order quote for my celebration list:

${itemList}
*Estimated Total:* ₹${totalPrice}

Please confirm order availability and dispatch schedule.
Looking forward to celebrating with Kallimatha Fireworks!`;

  return generateWhatsAppLink(message);
};

